function parseSubtagBlock(tsv: string): Map<string, SubtagRecord> {
  const map = new Map<string, SubtagRecord>();
  if (!tsv) return map;
  for (const line of tsv.split('\n')) {
    const [subtag, description, deprecated, preferredValue, prefixes, macrolanguage, suppressScript] = line.split('\t');
    map.set(subtag!.toLowerCase(), {
      subtag: subtag!,
      description: description ?? '',
      deprecated: deprecated === '1',
      preferredValue: preferredValue ? preferredValue : null,
      prefixes: prefixes ? prefixes.split('|') : [],
      macrolanguage: macrolanguage ? macrolanguage : null,
      suppressScript: suppressScript ? suppressScript : null,
    });
  }
  return map;
}

function parseTagBlock(tsv: string): Map<string, TagRecord> {
  const map = new Map<string, TagRecord>();
  if (!tsv) return map;
  for (const line of tsv.split('\n')) {
    const [tag, description, deprecated, preferredValue] = line.split('\t');
    map.set(tag!.toLowerCase(), {
      tag: tag!,
      description: description ?? '',
      deprecated: deprecated === '1',
      preferredValue: preferredValue ? preferredValue : null,
    });
  }
  return map;
}

const SUBTAG_TABLES: Record<SubtagType, Map<string, SubtagRecord>> = {
  language: parseSubtagBlock(LANGUAGE_TSV),
  extlang: parseSubtagBlock(EXTLANG_TSV),
  script: parseSubtagBlock(SCRIPT_TSV),
  region: parseSubtagBlock(REGION_TSV),
  variant: parseSubtagBlock(VARIANT_TSV),
};

const TAG_TABLES: Record<TagType, Map<string, TagRecord>> = {
  grandfathered: parseTagBlock(GRANDFATHERED_TSV),
  redundant: parseTagBlock(REDUNDANT_TSV),
};

/** Looks up a subtag of a given type, case-insensitively. Returns null when not registered. */
export function lookupSubtag(type: SubtagType, subtag: string): SubtagRecord | null {
  return SUBTAG_TABLES[type].get(subtag.toLowerCase()) ?? null;
}

/**
 * Looks up a complete tag among the grandfathered and redundant records,
 * case-insensitively. Returns null when the tag is not one of those
 * registrations (this is NOT a general tag validator -- ordinary tags are
 * validated subtag by subtag via lookupSubtag).
 */
export function lookupTag(tag: string): TagRecord | null {
  return TAG_TABLES.grandfathered.get(tag.toLowerCase()) ?? TAG_TABLES.redundant.get(tag.toLowerCase()) ?? null;
}
