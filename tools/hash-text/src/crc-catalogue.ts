/**
 * The CRC-16 and CRC-32 algorithms of the CRC Catalogue.
 *
 * Every parameter, name, other name and check value below is a published fact copied from the catalogue's pages
 * https://reveng.sourceforge.io/crc-catalogue/16.htm (last updated 11 December 2024) and
 * https://reveng.sourceforge.io/crc-catalogue/17plus.htm, read on 2026-10-03: 31 algorithms of width 16 and 12 of
 * width 32, listed in the catalogue's name order. The other names are the catalogue's own aliases, which is how
 * people search for them (for example CRC-16/IBM-3740 was long called CRC-16/CCITT-FALSE and CRC-32/ISCSI is CRC-32C).
 *
 * Each entry is the Rocksoft model: the width in bits, the polynomial in normal form with its top bit left out, the
 * register's initial value, whether input bytes and the result are bit-reflected, and a value exclusive-ored into the
 * result. `check` is the CRC of the nine ASCII bytes 123456789, which the unit tests reproduce for every entry.
 */
export interface CrcParams {
  name: string;
  aliases: string[];
  width: 16 | 32;
  poly: number;
  init: number;
  refin: boolean;
  refout: boolean;
  xorout: number;
  check: number;
}

