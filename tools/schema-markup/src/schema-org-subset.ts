function parseTypes(tsv: string): Map<string, TypeRecord> {
  const map = new Map<string, TypeRecord>();
  for (const line of tsv.split('\n')) {
    const [name, parents, props] = line.split('\t');
    map.set(name!, { parents: parents ? parents.split('|') : [], properties: props ? props.split('|') : [] });
  }
  return map;
}

function parseProperties(tsv: string): Map<string, PropertyRecord> {
  const map = new Map<string, PropertyRecord>();
  for (const line of tsv.split('\n')) {
    const [name, ranges] = line.split('\t');
    map.set(name!, { ranges: ranges ? ranges.split('|') : [] });
  }
  return map;
}

const TYPE_TABLE = parseTypes(TYPES_TSV);
const PROPERTY_TABLE = parseProperties(PROPERTIES_TSV);

/** Every bundled type name, in the order the subset module lists them. */
export const TYPES: ReadonlyMap<string, TypeRecord> = TYPE_TABLE;

/** Every bundled property name and its range type names. */
export const PROPERTIES: ReadonlyMap<string, PropertyRecord> = PROPERTY_TABLE;

/** True when `child` is `ancestor` itself or has `ancestor` anywhere in its parent chain. */
export function isSubtypeOf(child: string, ancestor: string): boolean {
  if (child === ancestor) return true;
  const record = TYPE_TABLE.get(child);
  if (!record) return false;
  return record.parents.includes(ancestor);
}
